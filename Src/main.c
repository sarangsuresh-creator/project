void ADC_Process(void){

	if (adc_half_ready == 1)
		      {
		          adc_half_ready = 0;

		          uint32_t sum = 0;

		          for (int i = 0; i < 8; i++)
		          {
		              sum += adc_buffer[i];
		          }

		          filtered_adc = sum / 8;
		      }


		      /* Second half of ADC DMA */
		      if (adc_full_ready == 1)
		      {
		          adc_full_ready = 0;

		          uint32_t sum = 0;

		          for (int i = 8; i < 16; i++)
		          {
		              sum += adc_buffer[i];
		          }

		          filtered_adc = sum / 8;
		      }


}
void UART_Process(unsigned int pwmDC){
	 if ((system_paused == 0) &&(HAL_GetTick() - last_uart_time >= 100) && (uart_tx_complete == 1))
		      {
		          last_uart_time = HAL_GetTick();

		          int len = sprintf(uart_tx_buffer,"ADC AVG: %u  PWM: %u %%\r\n",filtered_adc,pwmDC/10);

		          uart_tx_complete = 0;

		          HAL_UART_Transmit_DMA(&huart1,(uint8_t *)uart_tx_buffer,len);
		      }
}
unsigned int PWM_Process(void){
	 unsigned int pwm_value=0;
	 if (system_paused == 0)
		      {
		    	  pwm_value = (filtered_adc * 1000)/4095;

		          __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,pwm_value);
		      }
		      else
		      {
		          __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,0);
		      }
	 return pwm_value;
}
void button_debounce_check(void){
	   current_time = HAL_GetTick();
	       if (((current_time - last_button_time) >=5) && (button_pending == 1))
	       {
	    	   count2++;
	    	   if(HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_0)== GPIO_PIN_SET){
	    		 count1++;
	    	   }
	    	   if(count2 == 10) {
	    		   if(count1 >= 7){
	    			 system_paused ^= 1;

	    		   }
	    		   button_pending = 0;
	    		   count1 = count2 = 0;
	    	   }


	    	   last_button_time = current_time ;
	  }
}


